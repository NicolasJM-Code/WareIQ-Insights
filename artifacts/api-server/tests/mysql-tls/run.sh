#!/usr/bin/env bash
set -euo pipefail

script_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
repo_root="$(cd "$script_dir/../../../.." && pwd)"
compose_file="$script_dir/compose.yaml"
temp_root="$(cd "${TMPDIR:-/tmp}" && pwd -P)"
fixture_dir=""
fixture_lock_fd=""
project_name="wareiq-mysql-tls-$$"
compose=(docker compose --project-name "$project_name" -f "$compose_file")
# Reviewed 2026-10-29: test vendor-maintained MySQL 8 release lines only.
# MySQL 8.0 reached EOL with 8.0.46 in April 2026; 8.4 is the supported 8.x LTS.
# Recheck these sources when the vendor support policy changes:
# https://dev.mysql.com/doc/relnotes/mysql/8.0/en/
# https://dev.mysql.com/doc/refman/8.4/en/mysql-releases.html
mysql_release_lines=(8.4)

cleanup() {
  if [[ -n "$fixture_dir" ]]; then
    if WMS_MYSQL_TLS_FIXTURE_DIR="$fixture_dir" \
      WMS_MYSQL_TLS_FIXTURE_PID="$$" \
      "${compose[@]}" down --volumes --remove-orphans >/dev/null 2>&1; then
      rm -rf -- "$fixture_dir"
    else
      echo "Could not stop the disposable MySQL fixture; preserving its certificate directory at $fixture_dir." >&2
    fi
  fi
}
trap cleanup EXIT
trap 'exit 130' INT
trap 'exit 143' TERM

if ! command -v docker >/dev/null 2>&1 || ! docker compose version >/dev/null 2>&1; then
  echo "Docker Compose is required for the isolated MySQL TLS fixture." >&2
  exit 1
fi
if ! command -v flock >/dev/null 2>&1; then
  echo "flock is required to protect active disposable MySQL fixtures." >&2
  exit 1
fi
if ! command -v openssl >/dev/null 2>&1; then
  echo "OpenSSL is required to generate temporary fixture certificates." >&2
  exit 1
fi

recover_stale_fixtures() {
  local container_id metadata candidate_project owner_pid candidate_dir
  local member_id member_metadata member_project member_owner member_dir member_service
  local lock_file lock_fd
  local -a fixture_containers project_containers
  local -A checked_projects=()

  mapfile -t fixture_containers < <(
    docker ps --all --quiet --filter label=com.wareiq.mysql-tls.fixture=true
  )
  for container_id in "${fixture_containers[@]}"; do
    metadata="$(docker inspect --format \
      '{{ index .Config.Labels "com.docker.compose.project" }}|{{ index .Config.Labels "com.wareiq.mysql-tls.owner-pid" }}|{{ index .Config.Labels "com.wareiq.mysql-tls.fixture-dir" }}' \
      "$container_id" 2>/dev/null)" || continue
    IFS='|' read -r candidate_project owner_pid candidate_dir <<< "$metadata"

    [[ "$owner_pid" =~ ^[0-9]+$ ]] || continue
    [[ "$candidate_project" == "wareiq-mysql-tls-$owner_pid" ]] || continue
    kill -0 "$owner_pid" 2>/dev/null && continue
    [[ -z "${checked_projects[$candidate_project]+present}" ]] || continue
    checked_projects[$candidate_project]=1

    # The temp path is generated by this runner. Validate its shape and reject
    # symlinks before opening a lock file or removing anything. Do not require
    # the current TMPDIR; it may differ from the directory used by the old run.
    [[ "$candidate_dir" == /* ]] || continue
    [[ "${candidate_dir##*/}" =~ ^wareiq-mysql-tls\.[A-Za-z0-9]+$ ]] || continue
    [[ "$candidate_dir" != *"/../"* && "$candidate_dir" != */.. ]] || continue
    [[ -d "$candidate_dir" && ! -L "$candidate_dir" ]] || continue
    lock_file="$candidate_dir/.runner.lock"
    [[ -f "$lock_file" && ! -L "$lock_file" ]] || continue

    mapfile -t project_containers < <(
      docker ps --all --quiet --filter "label=com.docker.compose.project=$candidate_project"
    )
    ((${#project_containers[@]} > 0)) || continue

    # A project-name collision must not let cleanup remove unrelated containers.
    local project_is_owned=true
    for member_id in "${project_containers[@]}"; do
      member_metadata="$(docker inspect --format \
        '{{ index .Config.Labels "com.docker.compose.project" }}|{{ index .Config.Labels "com.wareiq.mysql-tls.fixture" }}|{{ index .Config.Labels "com.wareiq.mysql-tls.owner-pid" }}|{{ index .Config.Labels "com.wareiq.mysql-tls.fixture-dir" }}|{{ index .Config.Labels "com.docker.compose.service" }}' \
        "$member_id" 2>/dev/null)" || {
          project_is_owned=false
          break
        }
      IFS='|' read -r member_project member_fixture member_owner member_dir member_service <<< "$member_metadata"
      if [[ "$member_project" != "$candidate_project" ||
            "$member_fixture" != true ||
            "$member_owner" != "$owner_pid" ||
            "$member_dir" != "$candidate_dir" ||
            ( "$member_service" != mysql && "$member_service" != mysql-second &&
              "$member_service" != mysql-renewed ) ]]; then
        project_is_owned=false
        break
      fi
    done
    [[ "$project_is_owned" == true ]] || continue

    # Keep this lock held through teardown. The runner and its test subprocesses
    # share the lock's open file description, so cleanup cannot stop an active run.
    local recovery_status
    if (
      exec {lock_fd}> "$lock_file"
      flock -n "$lock_fd" || exit 10
      WMS_MYSQL_TLS_FIXTURE_DIR="$candidate_dir" \
        WMS_MYSQL_TLS_FIXTURE_PID="$owner_pid" \
        docker compose --project-name "$candidate_project" -f "$compose_file" \
          down --volumes --remove-orphans >/dev/null 2>&1 || exit 11
      rm -rf -- "$candidate_dir"
    ); then
      echo "Removed stale disposable MySQL fixture $candidate_project."
    else
      recovery_status=$?
      if [[ "$recovery_status" != 10 ]]; then
        echo "Could not recover stale disposable MySQL fixture $candidate_project; leaving its files in place." >&2
      fi
    fi
  done
}

recover_stale_fixtures
fixture_dir="$(mktemp -d "$temp_root/wareiq-mysql-tls.XXXXXX")"
export WMS_MYSQL_TLS_FIXTURE_DIR="$fixture_dir"
export WMS_MYSQL_TLS_FIXTURE_PID="$$"
exec {fixture_lock_fd}> "$fixture_dir/.runner.lock"
flock -n "$fixture_lock_fd"

fixture_gid="$(id -g)"
chmod 755 "$fixture_dir"
for certs in "$fixture_dir/certs" "$fixture_dir/certs-second" "$fixture_dir/certs-renewed"; do
mkdir -p "$certs"
chmod 770 "$certs"
openssl req -x509 -newkey rsa:2048 -sha256 -nodes -days 2 \
  -keyout "$certs/ca-key.pem" \
  -out "$certs/ca.pem" \
  -subj "/CN=WareIQ disposable MySQL $(basename "$certs") CA" \
  -addext "basicConstraints=critical,CA:TRUE" \
  -addext "keyUsage=critical,keyCertSign,cRLSign" 2>/dev/null
docker run --rm --user 999:999 --group-add "$fixture_gid" \
  --volume "$certs:/certs" \
  --entrypoint openssl "mysql:${mysql_release_lines[0]}" req -newkey rsa:2048 -sha256 -nodes \
  -keyout /certs/server-key.pem -out /certs/server.csr \
  -subj "/CN=mysql.fixture.test" 2>/dev/null
chmod 755 "$certs"
printf '%s\n' \
  'subjectAltName=DNS:mysql.fixture.test' \
  'extendedKeyUsage=serverAuth' \
  'keyUsage=digitalSignature,keyEncipherment' \
  > "$certs/server.ext"
openssl x509 -req -in "$certs/server.csr" \
  -CA "$certs/ca.pem" -CAkey "$certs/ca-key.pem" \
  -CAcreateserial -out "$certs/server-cert.pem" -days 2 -sha256 \
  -extfile "$certs/server.ext" 2>/dev/null
chmod 644 "$certs/server-cert.pem" "$certs/ca.pem"
done
connector_certs="$fixture_dir/connector-certs"
mkdir -p "$connector_certs"
openssl req -x509 -newkey rsa:2048 -sha256 -nodes -days 2 \
  -keyout "$connector_certs/ca-key.pem" \
  -out "$connector_certs/ca.pem" \
  -subj "/CN=WareIQ disposable connector HTTPS CA" \
  -addext "basicConstraints=critical,CA:TRUE" \
  -addext "keyUsage=critical,keyCertSign,cRLSign" 2>/dev/null
openssl req -newkey rsa:2048 -sha256 -nodes \
  -keyout "$connector_certs/server-key.pem" \
  -out "$connector_certs/server.csr" \
  -subj "/CN=connector.fixture.test" 2>/dev/null
printf '%s\n' \
  'subjectAltName=DNS:connector.fixture.test' \
  'extendedKeyUsage=serverAuth' \
  'keyUsage=digitalSignature,keyEncipherment' \
  > "$connector_certs/server.ext"
openssl x509 -req -in "$connector_certs/server.csr" \
  -CA "$connector_certs/ca.pem" -CAkey "$connector_certs/ca-key.pem" \
  -CAcreateserial -out "$connector_certs/server-cert.pem" -days 2 -sha256 \
  -extfile "$connector_certs/server.ext" 2>/dev/null
chmod 644 "$connector_certs/ca.pem" "$connector_certs/server-cert.pem"
openssl req -x509 -newkey rsa:2048 -sha256 -nodes -days 2 \
  -keyout "$fixture_dir/certs/untrusted-ca-key.pem" \
  -out "$fixture_dir/certs/untrusted-ca.pem" \
  -subj "/CN=WareIQ unrelated disposable MySQL CA" \
  -addext "basicConstraints=critical,CA:TRUE" \
  -addext "keyUsage=critical,keyCertSign,cRLSign" 2>/dev/null
chmod 644 "$fixture_dir/certs/server-cert.pem" "$fixture_dir/certs/ca.pem" \
  "$fixture_dir/certs/untrusted-ca.pem"

for release_line in "${mysql_release_lines[@]}"; do
  image="mysql:$release_line"
  export WMS_MYSQL_TLS_IMAGE="$image"
  echo "Starting secure-connection integration checks on ${image}."
  if ! "${compose[@]}" up --detach; then
    echo "MySQL ${image#mysql:} fixture startup failed; raw container logs were withheld." >&2
    exit 1
  fi

  fixture_port=""
  second_fixture_port=""
  renewed_fixture_port=""
  for service in mysql mysql-second mysql-renewed; do
    published_address="$("${compose[@]}" port "$service" 3306 | head -n 1)"
    port="${published_address##*:}"
    if [[ ! "$port" =~ ^[0-9]+$ ]]; then
      echo "MySQL ${image#mysql:}: could not determine the loopback-only fixture port." >&2
      exit 1
    fi
    case "$service" in
      mysql) fixture_port="$port" ;;
      mysql-second) second_fixture_port="$port" ;;
      mysql-renewed) renewed_fixture_port="$port" ;;
    esac
    container_id="$("${compose[@]}" ps -q "$service")"
    ready=false
    for _ in $(seq 1 120); do
      if docker logs "$container_id" 2>&1 | grep -q 'ready for connections.*port: 3306'; then
        ready=true
        break
      fi
      sleep 1
    done
    if [[ "$ready" != true ]]; then
      echo "MySQL ${image#mysql:}: fixture did not become ready within 120 seconds; raw container logs were withheld." >&2
      exit 1
    fi
  done

  container_id="$("${compose[@]}" ps -q mysql)"
  server_version="$(docker logs "$container_id" 2>&1 |
    sed -n "s/.*Version: '\\([0-9][0-9.]*\\)'.*/\\1/p" | head -n 1)"
  if [[ ! "$server_version" =~ ^[0-9]+\.[0-9]+\.[0-9]+$ ||
        "${server_version%.*}" != "$release_line" ]]; then
    echo "Expected MySQL ${release_line}.x but could not identify the server version for ${image}." >&2
    exit 1
  fi

  echo "Running secure-connection assertions against MySQL ${server_version}."
  cd "$repo_root"
  if ! WMS_MYSQL_TLS_INTEGRATION=1 \
    WMS_OPENVPN_MYSQL_TLS_INTEGRATION=1 \
    WMS_MYSQL_TLS_FIXTURE_DIR="$fixture_dir" \
    WMS_MYSQL_TLS_FIXTURE_PORT="$fixture_port" \
    WMS_MYSQL_TLS_SECOND_FIXTURE_PORT="$second_fixture_port" \
    WMS_MYSQL_TLS_RENEWED_FIXTURE_PORT="$renewed_fixture_port" \
    WMS_MYSQL_TLS_FIXTURE_VERSION="$server_version" \
      pnpm exec vitest run --config vitest.mysql-tls.config.ts \
        artifacts/api-server/tests/mysql-tls/runner.test.ts \
        artifacts/api-server/tests/wms-mysql.tls.integration.test.ts \
        artifacts/api-server/tests/wms-openvpn-mysql.tls.integration.test.ts; then
    echo "MySQL ${server_version} secure-connection integration checks failed." >&2
    exit 1
  fi

  "${compose[@]}" down --volumes --remove-orphans >/dev/null
done
